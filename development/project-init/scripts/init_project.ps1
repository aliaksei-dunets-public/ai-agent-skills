<#
.SYNOPSIS
    Deterministic, non-destructive part of project-init (Windows PowerShell).

.DESCRIPTION
    Creates what is missing and never modifies or deletes anything that exists:
    folders, the .tmp/ line in .gitignore (append only), docs/README.md,
    AGENTS.md (only when absent), and a stub of the temp-files skill
    (SKILL.md with the original frontmatter and a pointer to the original; the
    skill is never copied). An existing AGENTS.md or a link in place of the stub
    is reported as [needs-review] and left untouched; the agent normalizes
    instructions afterwards with the user's confirmation.

    One line per item: [created|skipped|needs-review|would-create|failed] item - detail.
    Exit code 1 when any item failed, otherwise 0.

.PARAMETER ProjectRoot
    Existing project root.

.PARAMETER TempFilesPath
    Folder of the temp-files skill. Default: ../../temp-files relative to this
    script. Pass it explicitly when this skill is reached through a link.

.PARAMETER GitInit
    Run git init when <root>/.git is missing.

.PARAMETER Claude
    Also create .claude/ and .claude/skills/temp-files.

.PARAMETER DryRun
    Report what would be created without changing anything.
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)][string]$ProjectRoot,
    [string]$TempFilesPath = "",
    [switch]$GitInit,
    [switch]$Claude,
    [switch]$DryRun
)

$ErrorActionPreference = "Stop"

$Root = (Resolve-Path -LiteralPath $ProjectRoot).Path
$SkillDir = Split-Path -Parent $PSScriptRoot
if ([string]::IsNullOrWhiteSpace($TempFilesPath)) {
    $TempFilesPath = Join-Path (Split-Path -Parent $SkillDir) "temp-files"
}
$TemplatePath = Join-Path $SkillDir "assets\AGENTS.template.md"
$Utf8 = New-Object System.Text.UTF8Encoding($false)
$script:Failed = 0
$StubMarker = "stub generated by project-init"
$script:IgnoreLines = @(".tmp/")   # lines the .gitignore step makes sure are present

function Report([string]$Status, [string]$Item, [string]$Detail = "") {
    if ($Status -eq "failed") { $script:Failed++ }
    if ($Detail) { Write-Host "[$Status] $Item - $Detail" } else { Write-Host "[$Status] $Item" }
}

function Step([string]$Item, [scriptblock]$Body) {
    try { & $Body } catch { Report "failed" $Item $_.Exception.Message }
}

function Ensure-Dir([string]$Rel) {
    Step $Rel {
        $path = Join-Path $Root $Rel
        if (Test-Path -LiteralPath $path -PathType Container) { Report "skipped" $Rel; return }
        if (Test-Path -LiteralPath $path) { Report "failed" $Rel "exists and is not a folder"; return }
        if ($DryRun) { Report "would-create" $Rel; return }
        New-Item -ItemType Directory -Path $path -Force | Out-Null
        Report "created" $Rel
    }
}

# Creates a file only when absent. An existing file is never touched.
function Ensure-File([string]$Rel, [string]$Content, [string]$ExistingStatus = "skipped") {
    Step $Rel {
        $path = Join-Path $Root $Rel
        if (Test-Path -LiteralPath $path) { Report $ExistingStatus $Rel "exists, left untouched"; return }
        if ($DryRun) { Report "would-create" $Rel; return }
        [System.IO.File]::WriteAllText($path, $Content, $Utf8)
        Report "created" $Rel
    }
}

# Project-side stub of the temp-files skill: only the original frontmatter (so the
# agent can trigger the skill) and a pointer to the original SKILL.md. Nothing is
# copied. An existing folder with SKILL.md, or any link, is left untouched.
function Get-StubContent {
    $original = Join-Path $TempFilesPath "SKILL.md"
    $text = [System.IO.File]::ReadAllText($original)
    $match = [regex]::Match($text, '(?s)\A---\r?\n(.*?)\r?\n---')
    if (-not $match.Success) { throw "no frontmatter in $original" }
    if ($match.Value -notmatch '(?m)^name:\s*temp-files\s*$') {
        throw "$original is not the temp-files skill (frontmatter name differs)"
    }
    $frontmatter = ($match.Value -replace "`r`n", "`n")
    $folder = (Resolve-Path -LiteralPath $TempFilesPath).Path
    return "$frontmatter`n`n# Temporary Files (stub)`n`n" +
        "This is a $StubMarker. The skill itself lives outside the project;`n" +
        "read and follow it completely before creating any temporary file:`n`n" +
        "$folder\SKILL.md`n`n" +
        "In that file, <skill_path> means $folder`n"
}

function Ensure-Stub([string]$Rel) {
    Step $Rel {
        $dir = Join-Path $Root $Rel
        $item = Get-Item -LiteralPath $dir -Force -ErrorAction SilentlyContinue
        if ($item) {
            if ($item.Attributes -band [System.IO.FileAttributes]::ReparsePoint) {
                Report "needs-review" $Rel "is a link, not a stub; left untouched"
                return
            }
            if (-not $item.PSIsContainer) { Report "failed" $Rel "exists and is not a folder"; return }
            $existing = Join-Path $dir "SKILL.md"
            if (Test-Path -LiteralPath $existing) {
                # Our own stub holds a machine-local path: keep it out of git. A foreign copy is not ours to hide.
                if ([System.IO.File]::ReadAllText($existing).Contains($StubMarker)) { $script:IgnoreLines += "$Rel/" }
                Report "skipped" $Rel "SKILL.md exists"
                return
            }
        }
        if (-not (Test-Path -LiteralPath (Join-Path $TempFilesPath "SKILL.md"))) {
            Report "failed" $Rel "temp-files skill not found at $TempFilesPath"
            return
        }
        $content = Get-StubContent
        $script:IgnoreLines += "$Rel/"
        if ($DryRun) { Report "would-create" $Rel; return }
        if (-not (Test-Path -LiteralPath $dir)) { New-Item -ItemType Directory -Path $dir -Force | Out-Null }
        [System.IO.File]::WriteAllText((Join-Path $dir "SKILL.md"), $content, $Utf8)
        Report "created" $Rel "stub pointing to $TempFilesPath"
    }
}

# 1. git
Step ".git" {
    if (-not $GitInit) { return }
    if (Test-Path -LiteralPath (Join-Path $Root ".git")) { Report "skipped" ".git"; return }
    if ($DryRun) { Report "would-create" ".git"; return }
    & git -C $Root init --quiet
    if ($LASTEXITCODE -ne 0) { throw "git init exited with $LASTEXITCODE" }
    Report "created" ".git"
}

# 2. folders
Ensure-Dir "docs"
Ensure-Dir ".agents/skills"
Ensure-Dir ".tmp"
if ($Claude) { Ensure-Dir ".claude" }

# 3. docs and instruction files
Ensure-File "docs/README.md" "# Documentation`n`nTable of contents for project documentation.`n"
Step "AGENTS.md" {
    $template = [System.IO.File]::ReadAllText($TemplatePath)
    Ensure-File "AGENTS.md" $template "needs-review"
}

# 4. temp-files stubs
Ensure-Stub ".agents/skills/temp-files"
if ($Claude) { Ensure-Stub ".claude/skills/temp-files" }

# 5. .gitignore: append-only; .tmp/ and our own stub folders
Step ".gitignore" {
    $path = Join-Path $Root ".gitignore"
    $text = if (Test-Path -LiteralPath $path) { [System.IO.File]::ReadAllText($path) } else { $null }
    $have = @()
    if ($null -ne $text) { $have = @($text -split "`r?`n" | ForEach-Object { $_.Trim() }) }
    $missing = @($script:IgnoreLines | Where-Object {
        $bare = $_.TrimEnd("/")
        -not ($have | Where-Object { $_ -in @($bare, "$bare/", "/$bare", "/$bare/") })
    })
    if ($missing.Count -eq 0) { Report "skipped" ".gitignore" "entries already present"; return }
    $detail = "adds " + ($missing -join ", ")
    if ($DryRun) { Report "would-create" ".gitignore" $detail; return }
    $nl = if ($null -ne $text -and $text.Contains("`r`n")) { "`r`n" } else { "`n" }
    $prefix = if ($text -and -not $text.EndsWith("`n")) { $nl } else { "" }
    [System.IO.File]::AppendAllText($path, $prefix + (($missing -join $nl) + $nl), $Utf8)
    Report "created" ".gitignore" $detail
}

if ($script:Failed -gt 0) { exit 1 }
exit 0
